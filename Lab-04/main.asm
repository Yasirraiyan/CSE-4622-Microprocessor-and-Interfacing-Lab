.MODEL SMALL
.STACK 100H
.DATA
PROMPT  DB 'Enter a number between 2 and 9: $'
RESULT  DW 0
N_VAL   DB ?
.CODE
MAIN PROC
MOV AX, @DATA
MOV DS, AX
MOV AH, 09H
LEA DX, PROMPT
INT 21H
MOV AH, 01H
INT 21H
SUB AL, 30H
MOV N_VAL, AL
MOV AX, 0
MOV BL, 1
MOV CL, N_VAL
MOV SI, 1
SUM_LOOP:
MOV DX, SI
MUL DX
ADD BX, AX
INC SI
LOOP SUM_LOOP
MOV RESULT, BX
MOV AX, RESULT
MOV CX, 10
CALL PRINT_NUM
MOV AH, 4CH
INT 21H
MAIN ENDP
PRINT_NUM PROC
PUSH AX
PUSH BX
PUSH CX
PUSH DX
MOV BX, 10
X_LOOP:
XOR DX, DX
DIV BX
PUSH DX
CMP AX, 0
JNE X_LOOP
POP DX
ADD DL, 30H
MOV AH, 02H
INT 21H
POP DX
POP CX
POP BX
POP AX
RET
PRINT_NUM ENDP
END MAIN
